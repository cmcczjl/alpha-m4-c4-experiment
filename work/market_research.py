def write_requirements(data, filepath):
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write("# Market Research Requirements\n\n")
        f.write("Generated by Market Data Crawler\n\n")
        for item in data:
            f.write(f"## {item['title']}\n")
            f.write(f"- **Source:** {item['url']}\n")
            for point in item['points']:
                f.write(f"  - {point}\n")
            f.write("\n")

if __name__ == "__main__":
    target_file = "requirements.md"
    write_requirements(market_data, target_file)
    print(f"Successfully wrote {len(market_data)} market insights to {target_file}")